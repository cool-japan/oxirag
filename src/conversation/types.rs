//! Core types for the conversational RAG module.
//!
//! This module defines the fundamental data structures used to represent
//! multi-turn conversation state: turns, history, sessions, and errors.

use std::collections::HashMap;
use std::time::SystemTime;

use serde::{Deserialize, Serialize};
use thiserror::Error;
use uuid::Uuid;

// ── TurnRole ───────────────────────────────────────────────────────────────────

/// The role of a participant in a conversation turn.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum TurnRole {
    /// A message from the end user.
    User,
    /// A message generated by the assistant (RAG pipeline output).
    Assistant,
}

impl std::fmt::Display for TurnRole {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::User => write!(f, "User"),
            Self::Assistant => write!(f, "Assistant"),
        }
    }
}

// ── Turn ──────────────────────────────────────────────────────────────────────

/// A single turn in a conversation, capturing the speaker, text, timestamp,
/// and arbitrary metadata.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Turn {
    /// Who produced this turn.
    pub role: TurnRole,
    /// The textual content of this turn.
    pub text: String,
    /// Wall-clock time when the turn was recorded.
    #[serde(with = "system_time_serde")]
    pub timestamp: SystemTime,
    /// Arbitrary metadata attached to this turn (e.g. model name, `latency_ms`).
    pub metadata: HashMap<String, String>,
}

impl Turn {
    /// Create a new turn with the current timestamp and empty metadata.
    #[must_use]
    pub fn new(role: TurnRole, text: impl Into<String>) -> Self {
        Self {
            role,
            text: text.into(),
            timestamp: SystemTime::now(),
            metadata: HashMap::new(),
        }
    }

    /// Builder-style method to attach metadata to a turn.
    #[must_use]
    pub fn with_metadata(mut self, key: impl Into<String>, value: impl Into<String>) -> Self {
        self.metadata.insert(key.into(), value.into());
        self
    }

    /// Return `true` if this turn was produced by the user.
    #[must_use]
    pub fn is_user(&self) -> bool {
        self.role == TurnRole::User
    }

    /// Return `true` if this turn was produced by the assistant.
    #[must_use]
    pub fn is_assistant(&self) -> bool {
        self.role == TurnRole::Assistant
    }
}

// ── SystemTime serde helpers ──────────────────────────────────────────────────

/// Serde helpers that serialise a `SystemTime` as seconds-since-UNIX-epoch (u64).
mod system_time_serde {
    use std::time::{Duration, SystemTime, UNIX_EPOCH};

    use serde::{Deserialize, Deserializer, Serializer};

    pub(super) fn serialize<S: Serializer>(t: &SystemTime, s: S) -> Result<S::Ok, S::Error> {
        let secs = t
            .duration_since(UNIX_EPOCH)
            .unwrap_or(Duration::ZERO)
            .as_secs();
        s.serialize_u64(secs)
    }

    pub(super) fn deserialize<'de, D: Deserializer<'de>>(d: D) -> Result<SystemTime, D::Error> {
        let secs = u64::deserialize(d)?;
        Ok(UNIX_EPOCH + Duration::from_secs(secs))
    }
}

// ── ConversationHistory ───────────────────────────────────────────────────────

/// An ordered, append-only log of conversation [`Turn`]s.
///
/// The history is the single source of truth for a conversation: all context
/// building and query reformulation operates over it.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct ConversationHistory {
    turns: Vec<Turn>,
}

impl ConversationHistory {
    /// Create an empty conversation history.
    #[must_use]
    pub fn new() -> Self {
        Self { turns: Vec::new() }
    }

    /// Append a new turn to the history.
    pub fn add_turn(&mut self, turn: Turn) {
        self.turns.push(turn);
    }

    /// Return a reference to the most recent user turn, if any.
    #[must_use]
    pub fn last_user_turn(&self) -> Option<&Turn> {
        self.turns.iter().rev().find(|t| t.is_user())
    }

    /// Return a reference to the most recent assistant turn, if any.
    #[must_use]
    pub fn last_assistant_turn(&self) -> Option<&Turn> {
        self.turns.iter().rev().find(|t| t.is_assistant())
    }

    /// Total number of turns in the history.
    #[must_use]
    pub fn len(&self) -> usize {
        self.turns.len()
    }

    /// Return `true` if there are no turns in the history.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.turns.is_empty()
    }

    /// Return the last `n` turns (or all turns if fewer than `n` exist).
    /// The returned slice is in chronological order.
    #[must_use]
    pub fn recent_turns(&self, n: usize) -> &[Turn] {
        let len = self.turns.len();
        let start = len.saturating_sub(n);
        &self.turns[start..]
    }

    /// Iterate over all turns in chronological order.
    pub fn iter(&self) -> std::slice::Iter<'_, Turn> {
        self.turns.iter()
    }

    /// Access all turns as a slice (used internally by buffer implementations).
    #[must_use]
    pub(crate) fn as_slice(&self) -> &[Turn] {
        &self.turns
    }

    /// Truncate the history to the most recent `max_turns` turns, discarding
    /// the oldest turns. This is used by `InMemorySessionManager` when a
    /// session's `max_turns` limit is exceeded.
    pub(crate) fn truncate_to(&mut self, max_turns: usize) {
        let len = self.turns.len();
        if len > max_turns {
            let excess = len - max_turns;
            self.turns.drain(0..excess);
        }
    }
}

impl<'a> IntoIterator for &'a ConversationHistory {
    type Item = &'a Turn;
    type IntoIter = std::slice::Iter<'a, Turn>;

    fn into_iter(self) -> Self::IntoIter {
        self.turns.iter()
    }
}

// ── ConversationId ────────────────────────────────────────────────────────────

/// A unique, opaque identifier for a conversation session.
///
/// Internally stores the UUID as a hyphenated string so that serde works
/// without requiring the `uuid/serde` feature flag.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct ConversationId(String);

impl ConversationId {
    /// Generate a fresh, random conversation ID.
    #[must_use]
    pub fn new() -> Self {
        Self(Uuid::new_v4().to_string())
    }

    /// Return the ID as a hyphenated UUID string.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl Default for ConversationId {
    fn default() -> Self {
        Self::new()
    }
}

impl std::fmt::Display for ConversationId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.0)
    }
}

// ── SessionConfig ─────────────────────────────────────────────────────────────

/// Per-session configuration that controls history size and summary behaviour.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SessionConfig {
    /// Maximum number of turns to retain in-memory before the oldest turns are
    /// discarded. Defaults to `100`.
    pub max_turns: usize,

    /// When the history exceeds this many turns the `SummaryBuffer` will
    /// compress older turns into a rolling plain-text summary.  Defaults to
    /// `10`.
    pub summary_threshold: usize,
}

impl Default for SessionConfig {
    fn default() -> Self {
        Self {
            max_turns: 100,
            summary_threshold: 10,
        }
    }
}

impl SessionConfig {
    /// Set the maximum number of turns.
    #[must_use]
    pub fn with_max_turns(mut self, max_turns: usize) -> Self {
        self.max_turns = max_turns;
        self
    }

    /// Set the summary threshold.
    #[must_use]
    pub fn with_summary_threshold(mut self, summary_threshold: usize) -> Self {
        self.summary_threshold = summary_threshold;
        self
    }
}

// ── Session ───────────────────────────────────────────────────────────────────

/// A complete conversation session, pairing a [`ConversationId`] with the
/// associated [`ConversationHistory`], creation time, and configuration.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Session {
    /// The unique identifier for this session.
    pub id: ConversationId,
    /// All turns that have occurred in this session.
    pub history: ConversationHistory,
    /// When the session was first created.
    #[serde(with = "system_time_serde")]
    pub created_at: SystemTime,
    /// Session-level configuration.
    pub config: SessionConfig,
}

impl Session {
    /// Create a brand-new session with a fresh ID.
    #[must_use]
    pub fn new(config: SessionConfig) -> Self {
        Self {
            id: ConversationId::new(),
            history: ConversationHistory::new(),
            created_at: SystemTime::now(),
            config,
        }
    }

    /// Create a session with a specific ID (useful for restoring persisted sessions).
    #[must_use]
    pub fn with_id(id: ConversationId, config: SessionConfig) -> Self {
        Self {
            id,
            history: ConversationHistory::new(),
            created_at: SystemTime::now(),
            config,
        }
    }

    /// Append a turn and enforce the `max_turns` limit.
    pub fn add_turn(&mut self, turn: Turn) {
        self.history.add_turn(turn);
        self.history.truncate_to(self.config.max_turns);
    }

    /// Return the number of turns in this session.
    #[must_use]
    pub fn turn_count(&self) -> usize {
        self.history.len()
    }
}

// ── ConversationError ─────────────────────────────────────────────────────────

/// Errors that can arise within the conversational RAG module.
#[derive(Debug, Error)]
pub enum ConversationError {
    /// No session was found for the given ID.
    #[error("Session not found: {0}")]
    SessionNotFound(String),

    /// The conversation history has grown too large to process.
    #[error("History too large: {0} turns")]
    HistoryTooLarge(usize),

    /// Query reformulation produced an unusable result.
    #[error("Reformulation failed: {0}")]
    ReformulationFailed(String),

    /// The supplied query string was empty.
    #[error("Empty query supplied")]
    EmptyQuery,

    /// The session store has reached its maximum capacity.
    #[error("Session store capacity exceeded: max {0} sessions")]
    CapacityExceeded(usize),

    /// A lock was poisoned by a previous panic.
    #[error("Internal lock error: {0}")]
    LockError(String),
}
