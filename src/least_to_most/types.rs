//! Types and traits for the `least_to_most` module.
//!
//! Least-to-Most Prompting (Zhou et al. 2022) decomposes a complex question
//! into an ordered sequence of simpler sub-problems — from least to most
//! complex — solves each in turn, feeding prior answers as context into
//! subsequent steps, and returns the full chain together with the final answer.
//!
//! The solver is supplied by the caller as the [`LtmSolver`] trait; a
//! deterministic [`MockLtmSolver`] is provided for testing.

use std::fmt;

use thiserror::Error;

// ── LtmConfig ─────────────────────────────────────────────────────────────────

/// Configuration for [`LtmEngine`](crate::least_to_most::engine::LtmEngine).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LtmConfig {
    /// Maximum number of sub-problems the engine will accept from decomposition.
    ///
    /// Defaults to `5`. When the solver returns more sub-problems than this
    /// limit the engine returns [`LtmError::SubproblemLimitExceeded`] without
    /// executing any solve steps.
    pub max_subproblems: usize,

    /// Maximum number of context documents forwarded to each solve step.
    ///
    /// Defaults to `3`. The engine scores all available documents by their
    /// token overlap with the current sub-question and forwards the top
    /// `max_context_docs` to [`LtmSolver::solve_step`].
    pub max_context_docs: usize,
}

impl Default for LtmConfig {
    fn default() -> Self {
        Self {
            max_subproblems: 5,
            max_context_docs: 3,
        }
    }
}

impl LtmConfig {
    /// Create a new configuration with default values.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Set the maximum number of sub-problems.
    #[must_use]
    pub fn with_max_subproblems(mut self, max_subproblems: usize) -> Self {
        self.max_subproblems = max_subproblems;
        self
    }

    /// Set the maximum number of context documents per solve step.
    #[must_use]
    pub fn with_max_context_docs(mut self, max_context_docs: usize) -> Self {
        self.max_context_docs = max_context_docs;
        self
    }
}

// ── LtmError ──────────────────────────────────────────────────────────────────

/// Errors from the `least_to_most` module.
#[derive(Debug, Error)]
pub enum LtmError {
    /// The decomposition step failed (e.g., the solver could not break down
    /// the query into sub-problems).
    #[error("decomposition failed: {0}")]
    DecompositionFailed(String),

    /// A solve step failed (e.g., the solver could not answer a sub-question).
    #[error("solve failed: {0}")]
    SolveFailed(String),

    /// The solver returned more sub-problems than `max_subproblems` allows.
    ///
    /// The inner value is the number of sub-problems that were returned.
    #[error("subproblem limit exceeded: {0} sub-problems")]
    SubproblemLimitExceeded(usize),
}

// ── SubProblem ────────────────────────────────────────────────────────────────

/// A single solved step in the Least-to-Most chain.
///
/// Each [`SubProblem`] records the sub-question generated by decomposition,
/// the answer produced for that sub-question, and the zero-based position of
/// this step within the overall chain.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SubProblem {
    /// The sub-question for this step.
    pub question: String,

    /// The answer generated for this sub-question.
    pub answer: String,

    /// Zero-based position of this step in the chain.
    ///
    /// The simplest sub-problem has `step_index = 0`; subsequent steps
    /// increment by one.
    pub step_index: usize,
}

impl SubProblem {
    /// Create a new sub-problem record.
    #[must_use]
    pub fn new(question: impl Into<String>, answer: impl Into<String>, step_index: usize) -> Self {
        Self {
            question: question.into(),
            answer: answer.into(),
            step_index,
        }
    }
}

// ── LtmResult ─────────────────────────────────────────────────────────────────

/// The complete result of a Least-to-Most Prompting run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LtmResult {
    /// The original query supplied by the caller.
    pub original_query: String,

    /// The ordered chain of sub-problems and their answers, from least to most
    /// complex.
    pub subproblems: Vec<SubProblem>,

    /// The final answer, taken from the last solve step in the chain.
    pub final_answer: String,
}

// ── LtmSolver ─────────────────────────────────────────────────────────────────

/// A model that decomposes a complex question and solves each sub-problem.
///
/// Implementations are **pure sync** — no I/O, no async. The caller supplies
/// a concrete implementation (e.g. wrapping an LLM); [`MockLtmSolver`] is
/// provided for testing.
///
/// # Object Safety
///
/// This trait is object-safe and may be stored as `Box<dyn LtmSolver>`.
pub trait LtmSolver: fmt::Debug {
    /// Decompose a complex query into an ordered list of simpler sub-questions.
    ///
    /// The returned sub-questions are ordered from least to most complex: the
    /// first question is the simplest prerequisite, and each subsequent
    /// question builds on previous ones.
    ///
    /// # Errors
    ///
    /// Returns [`LtmError::DecompositionFailed`] if the query cannot be
    /// decomposed.
    fn decompose(&self, query: &str) -> Result<Vec<String>, LtmError>;

    /// Solve a single sub-problem, given accumulated prior answers and
    /// context documents selected by the engine.
    ///
    /// `prior_answers` contains all [`SubProblem`]s solved so far (empty for
    /// the first step). `docs` is the slice of context documents chosen by
    /// the engine for this step.
    ///
    /// # Errors
    ///
    /// Returns [`LtmError::SolveFailed`] if the step cannot be completed.
    fn solve_step(
        &self,
        question: &str,
        prior_answers: &[SubProblem],
        docs: &[String],
    ) -> Result<String, LtmError>;
}

// ── MockLtmSolver ─────────────────────────────────────────────────────────────

/// Deterministic [`LtmSolver`] for tests.
///
/// ### Decompose
///
/// Splits the query into words and treats any word whose alphabetic characters
/// (case-insensitive) spell `"and"`, `"then"`, or `"also"` as a separator.
/// Segments between separators are joined with spaces and trimmed; empty
/// segments are discarded. When fewer than two non-empty segments result, the
/// whole (original) query is returned as a single-element list.
///
/// ### Solve step
///
/// Concatenates (in order) all received context documents followed by all
/// prior answers, joining them with `"; "`. The resulting context is formatted
/// as `"Context: <ctx> Answer: <question>"`. When neither docs nor prior
/// answers are present the output is simply `"Answer: <question>"`.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct MockLtmSolver;

impl MockLtmSolver {
    /// Create a new mock solver.
    #[must_use]
    pub fn new() -> Self {
        Self
    }
}

impl LtmSolver for MockLtmSolver {
    fn decompose(&self, query: &str) -> Result<Vec<String>, LtmError> {
        let separators = ["and", "then", "also"];

        let mut segments: Vec<String> = Vec::new();
        let mut current: Vec<&str> = Vec::new();

        for word in query.split_whitespace() {
            let lower = word.to_lowercase();
            let stripped: String = lower.chars().filter(|c| c.is_alphabetic()).collect();

            if separators.contains(&stripped.as_str()) {
                let segment = current.join(" ");
                if !segment.is_empty() {
                    segments.push(segment);
                }
                current.clear();
            } else {
                current.push(word);
            }
        }

        let tail = current.join(" ");
        if !tail.is_empty() {
            segments.push(tail);
        }

        if segments.len() <= 1 {
            return Ok(vec![query.to_string()]);
        }

        Ok(segments)
    }

    fn solve_step(
        &self,
        question: &str,
        prior_answers: &[SubProblem],
        docs: &[String],
    ) -> Result<String, LtmError> {
        let mut context_parts: Vec<String> = Vec::new();

        for doc in docs {
            context_parts.push(doc.clone());
        }

        for prior in prior_answers {
            context_parts.push(prior.answer.clone());
        }

        if context_parts.is_empty() {
            Ok(format!("Answer: {question}"))
        } else {
            Ok(format!(
                "Context: {} Answer: {question}",
                context_parts.join("; ")
            ))
        }
    }
}

// ── tokenize (internal, doc-hidden) ──────────────────────────────────────────

/// Tokenize `text` into lowercase alphanumeric tokens of length ≥ 2.
///
/// Used internally by [`LtmEngine`](crate::least_to_most::engine::LtmEngine)
/// to compute token overlap for context-document selection, and exposed for
/// unit testing.
#[doc(hidden)]
#[must_use]
pub fn tokenize(text: &str) -> Vec<String> {
    text.split(|c: char| !c.is_alphanumeric())
        .filter(|t| t.len() >= 2)
        .map(str::to_lowercase)
        .collect()
}
