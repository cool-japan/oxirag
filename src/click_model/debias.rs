//! [`DebiasedRanker`] — **unbiased learning to rank from biased implicit
//! feedback** (Joachims, Swaminathan & Schnabel, 2017, "Unbiased Learning-to-Rank
//! with Biased Feedback").
//!
//! # The construction
//!
//! From a click log, a *naive* pairwise learner reads off one preference per
//! `(clicked, not-clicked)` pair in a session and minimises the usual pairwise
//! logistic (`RankNet`) loss. That learner converges — enthusiastically — to the
//! **logging policy's own bias**, because a document at rank 0 wins those pairs
//! far more often than an equally good document at rank 9, purely by being
//! looked at more.
//!
//! The fix is a single, decisive multiplication. A pair generated by a click on
//! document `d⁺`, logged at rank `r`, is *itself* only observable with
//! probability `γ_r`. So weight it by `1 / γ_r`:
//!
//! ```text
//! L(w) = ( Σ_sessions Σ_{d⁺ clicked} Σ_{d⁻ not clicked}  (1/γ_{r(d⁺)}) ·
//!            ln(1 + exp(−(w·x_{d⁺} − w·x_{d⁻}))) )  /  Σ (1/γ_{r(d⁺)})
//!        + (λ/2)·‖w‖²
//! ```
//!
//! Under the examination hypothesis, `E[click at rank r] = γ_r · α_d`, so
//! `E[click / γ_r] = α_d` — the `γ_r` in the numerator (the probability of
//! *seeing* the pair) and the `1/γ_r` in the weight cancel **exactly**, and the
//! expected loss is the loss the learner would have paid on the *unbiased*
//! preferences it never got to see. The empirical risk minimiser of the weighted
//! loss is therefore consistent for the true ranking, from data that is
//! systematically lying to it.
//!
//! # Why the loss is exactly minimised, not approximately
//!
//! The score is linear (`s = w · x`), the pairwise logistic loss is convex in
//! the score difference, and the difference is linear in `w`; adding an `L2`
//! penalty makes the objective **strictly** convex. Full-batch gradient descent
//! with a sensibly small step therefore decreases the loss monotonically and
//! converges to the unique optimum. The tests assert the monotone decrease
//! directly. The `L2` term is not decoration: with one-hot features and a
//! document that never loses a pair, the unregularised optimum is at infinity.
//!
//! # Pair aggregation
//!
//! Because the score depends on the document alone, two pairs over the same
//! `(d⁺, d⁻)` differ only in their weight. The fitter therefore **aggregates**
//! them into one pair carrying the summed weight before the first gradient step.
//! This is exact — not an approximation — and it turns an `O(sessions × k²)`
//! inner loop into an `O(distinct pairs)` one.
//!
//! # How to get the *naive* learner for comparison
//!
//! Fit against [`PropensityEstimates::uniform`]. Every weight becomes `1`, the
//! correction disappears, and you have the biased baseline — which is exactly how
//! the module's tests show that it is the debiasing, and nothing else, that
//! recovers the true order.

